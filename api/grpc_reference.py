class LoggingInterceptor(grpc.ServerInterceptor):
    """Logs method, latency, and status for every RPC."""

    def intercept_service(self, continuation, handler_call_details):
        existing = continuation(handler_call_details)

        def _timed(behavior):
            def new_behavior(request_or_iterator, servicer_context: ServicerContext):
                start = _CLOCK()
                try:
                    return behavior(request_or_iterator, servicer_context)
                finally:
                    elapsed_ms = (_CLOCK() - start) * 1000
                    logger.info(
                        "gRPC %s completed in %.2f ms",
                        handler_call_details.method,
                        elapsed_ms,
                    )
            return new_behavior

        if existing is None:
            return existing

        return existing._replace(
            unary_unary=_timed(existing.unary_unary) if existing.unary_unary else None,
            unary_stream=_timed(existing.unary_stream) if existing.unary_stream else None,
            stream_unary=_timed(existing.stream_unary) if existing.stream_unary else None,
            stream_stream=_timed(existing.stream_stream) if existing.stream_stream else None,
        )


