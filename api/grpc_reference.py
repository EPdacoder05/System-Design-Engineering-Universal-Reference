def create_server(port: int = 50051, secret: str = "change-me") -> grpc.Server:
    """
    Assemble the gRPC server with all interceptors and services.
    Health + reflection are always registered for ops tooling.
    """
    interceptors = [
        JWTInterceptor(secret=secret),
        LoggingInterceptor(),
    ]

    server = grpc.server(
        futures.ThreadPoolExecutor(max_workers=int(os.getenv("GRPC_WORKERS", "10"))),
        interceptors=interceptors,
        options=[
            ("grpc.max_receive_message_length", 4 * 1024 * 1024),
            ("grpc.max_send_message_length", 4 * 1024 * 1024),
            ("grpc.so_reuseport", 1),          # allows multiple server processes on same port
        ],
    )

    # Register application service
    # user_pb2_grpc.add_UserServiceServicer_to_server(UserServiceServicer(), server)

    # Health checking
    health_servicer = health.HealthServicer(
        experimental_non_blocking=True,
        experimental_thread_pool=futures.ThreadPoolExecutor(max_workers=2),
    )
    health_pb2_grpc.add_HealthServicer_to_server(health_servicer, server)
    # Mark service healthy; integrate with your readiness probe
    health_servicer.set("user.UserService", health_pb2.HealthCheckResponse.SERVING)

    # Reflection (enable in dev, disable in production if API hiding is desired)
    SERVICE_NAMES = (
        # user_pb2.DESCRIPTOR.services_by_name["UserService"].full_name,
        health_pb2.DESCRIPTOR.services_by_name["Health"].full_name,
        reflection.SERVICE_NAME,
    )
    reflection.enable_server_reflection(SERVICE_NAMES, server)

    server.add_insecure_port(f"[::]:{port}")
    return server


