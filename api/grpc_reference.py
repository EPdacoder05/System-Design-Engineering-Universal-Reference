def create_mtls_channel(
    host: str,
    port: int,
    ca_cert_path: str,
    client_cert_path: str,
    client_key_path: str,
) -> grpc.Channel:
    """
    Create a secure gRPC channel with mutual TLS.
    Both server and client certificates must be signed by the same CA.
    Use for service-to-service calls in a zero-trust environment.
    """
    with open(ca_cert_path, "rb") as f:
        root_certs = f.read()
    with open(client_cert_path, "rb") as f:
        certificate_chain = f.read()
    with open(client_key_path, "rb") as f:
        private_key = f.read()

    credentials = grpc.ssl_channel_credentials(
        root_certificates=root_certs,
        private_key=private_key,
        certificate_chain=certificate_chain,
    )
    return grpc.secure_channel(f"{host}:{port}", credentials)


