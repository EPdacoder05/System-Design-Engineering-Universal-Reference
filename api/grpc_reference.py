def create_client_channel(host: str, port: int) -> grpc.Channel:
    """Insecure channel with retry policy (dev/internal-only)."""
    options = [
        ("grpc.service_config", RETRY_SERVICE_CONFIG),
        ("grpc.keepalive_time_ms", 30_000),       # send ping every 30 s
        ("grpc.keepalive_timeout_ms", 5_000),      # wait 5 s for pong
        ("grpc.keepalive_permit_without_calls", 1),
        ("grpc.max_receive_message_length", 4 * 1024 * 1024),  # 4 MiB
        ("grpc.max_send_message_length", 4 * 1024 * 1024),
    ]
    return grpc.insecure_channel(f"{host}:{port}", options=options)


